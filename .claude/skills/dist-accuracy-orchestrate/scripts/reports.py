"""Check accuracy reports against the template and build reports/INDEX.md.

Usage
-----
    python reports.py check reports/gamma.md     # exit 1 and list problems if malformed
    python reports.py status reports/*.md        # one line per report
    python reports.py index [--dir reports]      # (re)write reports/INDEX.md table
"""
import argparse
import glob
import os
import re
import sys

HEADINGS = [
    "## Summary",
    "## Findings",
    "## RuntimeWarnings",
    "## Checked and fine",
    "## Suspected, not confirmed",
    "## Opportunities: inherited methods",
    "## Shared code",
    "## Existing GitHub issues",
    "## Verification",
]
SEVERITIES = ["loss", "severe", "moderate", "minor"]
HEADER_FIELDS = ["SciPy version", "Source", "Implemented", "Inherited", "Reference", "Worst finding"]


def section(text, heading):
    i = text.find(heading)
    if i < 0:
        return ""
    rest = text[i + len(heading):]
    j = rest.find("\n## ")
    return rest if j < 0 else rest[:j]


def parse(path):
    text = open(path, encoding="utf-8").read()
    problems = []
    if not re.match(r"# \S+: numerical accuracy review", text):
        problems.append("first line must be '# <dist>: numerical accuracy review'")
    for f in HEADER_FIELDS:
        if f"**{f}" not in text.split("## Summary")[0]:
            problems.append(f"header field missing: {f}")
    for h in HEADINGS:
        if h not in text:
            problems.append(f"missing heading: {h}")
    findings = []
    for line in section(text, "## Findings").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 6 and re.fullmatch(r"F\d+", cells[0]):
            sev = cells[-1].lower()
            if sev not in SEVERITIES:
                problems.append(f"{cells[0]}: severity '{cells[-1]}' not one of {SEVERITIES}")
            findings.append({"id": cells[0], "methods": cells[1], "severity": sev,
                             "error": cells[-2].lower()})
    counts = {s: sum(f["severity"] == s for f in findings) for s in SEVERITIES}
    worst = next((s for s in SEVERITIES if counts[s]), "none")
    methods = sorted({m.strip() for f in findings for m in f["methods"].split(",") if m.strip()})
    opp = [l for l in section(text, "## Opportunities: inherited methods").splitlines()
           if l.startswith("|") and not set(l) <= set("|- ") and "Method" not in l]
    shared = section(text, "## Shared code").strip()
    ver = section(text, "## Verification")
    m = re.search(r"(\d+) of (\d+) verified", ver)
    verified = f"{m.group(1)}/{m.group(2)}" if m else ("pending" if "pending" in ver else "-")
    # Light reviews say so in the header or leave the reference/errors "not measured";
    # a full review may still mention "not measured" for one regime in its Findings.
    header = text.split("## Summary")[0].lower()
    ref = re.search(r"\*\*reference:\*\*(.*)", header)
    light = ("light review" in header
             or bool(ref and ref.group(1).strip().startswith("not measured"))
             or bool(findings and all("not measured" in f["error"] for f in findings)))
    return dict(name=os.path.basename(path)[:-3], problems=problems, findings=findings,
                counts=counts, worst=worst, methods=methods, opportunities=len(opp),
                shared=not (shared.lower().startswith("none") or shared == ""),
                verified=verified, light=light)


def cmd_check(paths):
    bad = False
    for p in paths:
        r = parse(p)
        if r["problems"]:
            bad = True
            print(f"{p}: MALFORMED")
            for q in r["problems"]:
                print(f"  - {q}")
        else:
            print(f"{p}: ok ({len(r['findings'])} findings, worst: {r['worst']}, verification: {r['verified']})")
    sys.exit(1 if bad else 0)


def cmd_status(paths):
    for p in paths:
        r = parse(p)
        c = r["counts"]
        print(f"{r['name']:20} worst={r['worst']:9} loss={c['loss']} severe={c['severe']} "
              f"moderate={c['moderate']} minor={c['minor']} verified={r['verified']}"
              + ("  MALFORMED" if r["problems"] else ""))


def cmd_index(d):
    rows = [parse(p) for p in sorted(glob.glob(os.path.join(d, "*.md")))
            if os.path.basename(p) != "INDEX.md"]
    order = {s: i for i, s in enumerate(SEVERITIES + ["none"])}
    rows.sort(key=lambda r: (order[r["worst"]], -sum(r["counts"].values()), r["name"]))
    out = ["# Numerical accuracy review: index", "",
           "Generated by `reports.py index`; edit the sections below the table by hand.", "",
           "| Distribution | Worst | loss | severe | moderate | minor | Methods affected | Opportunities | Shared code | Verified |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        c = r["counts"]
        name = f"[{r['name']}]({r['name']}.md)" + (" (light)" if r["light"] else "")
        out.append(f"| {name} | {r['worst']} | {c['loss']} | {c['severe']} | {c['moderate']} | {c['minor']} | "
                   f"{', '.join(r['methods']) or '-'} | {r['opportunities']} | {'yes' if r['shared'] else '-'} | "
                   f"{r['verified']} |")
    table = "\n".join(out) + "\n"
    path = os.path.join(d, "INDEX.md")
    tail = ""
    if os.path.exists(path):
        old = open(path, encoding="utf-8").read()
        k = old.find("\n## ")
        tail = old[k:] if k >= 0 else ""
    if not tail:
        tail = ("\n## Cross-cutting issues\n\n(shared helpers, scipy.special functions, recurring patterns)\n"
                "\n## Notes\n\n")
    open(path, "w", encoding="utf-8").write(table + tail)
    print(f"wrote {path} ({len(rows)} reports)")


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check")
    c.add_argument("paths", nargs="+")
    s = sub.add_parser("status")
    s.add_argument("paths", nargs="+")
    i = sub.add_parser("index")
    i.add_argument("--dir", default="reports")
    a = p.parse_args()
    if a.cmd == "check":
        cmd_check(a.paths)
    elif a.cmd == "status":
        cmd_status(a.paths)
    else:
        cmd_index(a.dir)


if __name__ == "__main__":
    main()
